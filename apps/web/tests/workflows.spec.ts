import { expect, test } from "@playwright/test";

for (const width of [1440, 390]) {
  test(`workflow fields, dated runs and consolidated records at ${width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 1000 });
    await page.goto("/");
    await page.getByRole("button", { name: "New here? Create an account" }).click();
    await page.getByLabel("Email", { exact: true }).fill(`workflow-${crypto.randomUUID()}@example.com`);
    await page.getByLabel("Password", { exact: true }).fill("synthetic workflow passphrase");
    await page.getByRole("button", { name: "Create account", exact: true }).click();
    await page.getByRole("navigation").getByRole("button", { name: "Workflows" }).click();
    await page.getByRole("button", { name: "Create workflow", exact: true }).click();
    await page.getByLabel("Workflow name", { exact: true }).fill("Synthetic field workflow");
    await page.getByRole("button", { name: "+ Add field", exact: true }).click();
    const custom = page.locator(".field-definition").last();
    await custom.getByLabel("Field key", { exact: true }).fill("focus_area");
    await custom.getByLabel("Field label", { exact: true }).fill("Focus area");
    await custom.getByLabel("AI extraction instruction", { exact: true }).fill("Explicit focus only");
    await page.getByRole("button", { name: "Save workflow", exact: true }).click();
    const downloaded = page.waitForEvent("download");
    await page.getByRole("button", { name: "Download DSL & JSONata" }).click();
    expect((await downloaded).suggestedFilename()).toMatch(/^workflow-.*-v1\.json$/);
    await page.getByRole("button", { name: "Start a run", exact: true }).click();
    await page.getByLabel("Run name", { exact: true }).fill("Yesterday test");
    await page.getByLabel("Session intention").fill("Synthetic first day");
    await page.getByRole("button", { name: /Start run/ }).click();
    await page.getByRole("button", { name: "+ Add a quick manual capture" }).click();
    await page.getByLabel("Contact URL", { exact: true }).fill("https://linkedin.com/in/synthetic-mira");
    await page.getByLabel("Raw capture text", { exact: true }).fill("Name: Mira Example\nCompany: Synthetic Labs\nRole: CTO\nFocus area: Fintech");
    await page.getByRole("button", { name: "Capture for review", exact: true }).click();
    await page.getByRole("button", { name: "Close manual capture" }).click();
    await page.getByRole("button", { name: "Process with AI", exact: true }).click();
    await expect(page.getByText(/Local fallback · 4 fields filled/)).toBeVisible();
    await page.getByRole("button", { name: "Finish & review" }).click();
    await expect(page.getByLabel("Name", { exact: true })).toHaveValue("Mira Example");
    await expect(page.getByLabel("Focus area", { exact: true })).toHaveValue("Fintech");
    await page.getByRole("button", { name: "Approve record", exact: true }).click();
    await page.getByRole("button", { name: "Complete session", exact: true }).click();
    await page.getByRole("navigation").getByRole("button", { name: "Workflows" }).click();
    await page.locator(".workflow-card").filter({ hasText: "Synthetic field workflow" }).click();
    await page.getByRole("button", { name: "Start a run", exact: true }).click();
    await page.getByLabel("Run name", { exact: true }).first().fill("Today test");
    await page.getByLabel("Session intention").fill("Synthetic second day");
    await page.getByRole("button", { name: /Start run/ }).click();
    await page.getByRole("button", { name: "+ Add a quick manual capture" }).click();
    await page.getByLabel("Contact URL", { exact: true }).fill("https://www.linkedin.com/in/synthetic-mira/?trk=test");
    await page.getByLabel("Name", { exact: true }).fill("Mira Example");
    await page.getByLabel("Focus area", { exact: true }).fill("Payments");
    await page.getByRole("button", { name: "Capture for review", exact: true }).click();
    await page.getByRole("button", { name: "Close manual capture" }).click();
    await page.getByLabel("Run name", { exact: true }).fill("Afternoon follow-ups");
    await page.getByRole("button", { name: "Rename run", exact: true }).click();
    await page.getByRole("navigation").getByRole("button", { name: "Workflows" }).click();
    await page.locator(".workflow-card").filter({ hasText: "Synthetic field workflow" }).click();
    await expect(page.getByRole("button", { name: /Afternoon follow-ups.*1 records/ })).toBeVisible();
    await page.getByRole("button", { name: "Consolidated records", exact: true }).click();
    await expect(page.getByText(/1 normalized contacts across 2 records/)).toBeVisible();
    await expect(page.getByRole("table")).toContainText("Mira Example");
    await expect(page.getByRole("table")).toContainText("Payments");
    await expect(page.getByRole("table")).toContainText("Yesterday test");
    await expect(page.getByRole("table")).toContainText("Afternoon follow-ups");
    await expect(page.getByRole("table")).toContainText("pending");
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(0);
    await page.screenshot({ path: testInfo.outputPath(`workflows-${width}.png`), fullPage: true });
  });
}
